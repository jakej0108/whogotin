-- university_domains: each school's website domain, used to show its logo.
--
-- Adds universities.domain (e.g. 'ucla.edu') and fills it for every school.
-- Logos are fetched from each school's own website once by
-- scripts/fetch-logos.mjs (run by the "Fetch university logos" GitHub
-- Action) and served from the repo's logos/ folder; schools without a
-- domain or logo keep showing their initials.
--
-- When you add a new school later, fill in its domain too, then run the
-- Action again.
--
-- Install: paste this whole file into Supabase -> SQL Editor -> Run.
-- Safe to run again.

alter table public.universities add column if not exists domain text;

alter table public.universities drop constraint if exists universities_domain_format;
alter table public.universities add constraint universities_domain_format
  check (domain is null or domain ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$');

